#!/usr/bin/env python3
"""Generate src/generated/settings.ts from the public settings in core/settings_registry.py.

The frontend's defaults, types and bounds for public settings come from this
file, never from a second hand-written copy (AGENTS.md rule 11).

    npm run settings:build    # write src/generated/settings.ts
    npm run settings:check    # exit 1 if the file is out of date (CI)

Imports only core.settings_registry, which needs nothing beyond the standard
library, so it runs before the backend's dependencies are installed.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
ROOT = BACKEND.parent
OUT = ROOT / "src" / "generated" / "settings.ts"
sys.path.insert(0, str(BACKEND))

from core import settings_registry as R  # noqa: E402

TS_TYPES = {R.INT: "number", R.FLOAT: "number", R.BOOL: "boolean", R.STR: "string"}

HEADER = (
    "// GENERATED by backend/scripts/export_public_settings.py from backend/core/settings_registry.py.\n"
    "// Do not edit by hand: change the declaration and run `npm run settings:build`.\n"
    "// Only settings declared public are here; the rest never reach the client.\n"
)


def _ts_type(decl: R.Setting) -> str:
    if decl.type == R.ENUM or (decl.type == R.STR and decl.allowed):
        return " | ".join(json.dumps(v) for v in decl.allowed)
    return TS_TYPES[decl.type]


def render() -> str:
    decls = R.public_settings()
    lines = [HEADER, "export interface PublicSettings {"]
    for d in decls:
        lines.append(f"  /** {d.description}{f' ({d.unit})' if d.unit else ''} */")
        lines.append(f"  {json.dumps(d.key)}: {_ts_type(d)};")
    lines.append("}")
    lines.append("")
    lines.append("export type PublicSettingKey = keyof PublicSettings;")
    lines.append("")
    lines.append("type PublicSettingType = 'int' | 'float' | 'bool' | 'str' | 'enum';")
    lines.append("")
    lines.append("export interface PublicSettingSpec {")
    lines.append("  readonly type: PublicSettingType;")
    lines.append("  readonly min: number | null;")
    lines.append("  readonly max: number | null;")
    lines.append("  readonly allowed: readonly string[];")
    lines.append("  readonly unit: string;")
    lines.append("}")
    lines.append("")
    lines.append("export const publicSettingDefaults: Readonly<PublicSettings> = {")
    for d in decls:
        lines.append(f"  {json.dumps(d.key)}: {json.dumps(d.default)},")
    lines.append("};")
    lines.append("")
    lines.append("export const publicSettingSpecs: Readonly<Record<PublicSettingKey, PublicSettingSpec>> = {")
    for d in decls:
        spec = (f"type: {json.dumps(d.type)}, min: {json.dumps(d.minimum)}, max: {json.dumps(d.maximum)}, "
                f"allowed: {json.dumps(list(d.allowed))}, unit: {json.dumps(d.unit)}")
        lines.append(f"  {json.dumps(d.key)}: {{ {spec} }},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date with backend/core/settings_registry.py. "
                  "Run `npm run settings:build` and commit the result.", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)}: up to date ({len(R.public_settings())} public settings)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(R.public_settings())} public settings)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
